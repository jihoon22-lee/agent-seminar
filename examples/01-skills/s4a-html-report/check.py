"""s4a-html-report 검증. python check.py [--model]"""
import json
import re
import shutil
import subprocess
import sys
import pathlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "tools"))
from octest import Sandbox, check, finish, model_check, model_enabled, skill_loaded  # noqa: E402
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from fake_llm import FakeLLM  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
SCRIPT = ".opencode/skills/html-report/scripts/build_report.py"
OUT = HERE / "out" / "report.html"


def run(*args):
    return subprocess.run([sys.executable, "-X", "utf8", *map(str, args)], cwd=HERE,
                          capture_output=True, text=True, encoding="utf-8", timeout=60)


def scripted_skill_run(sb, cwd, skill, command, marker, label):
    """가짜 모델이 skill 도구 -> bash 도구 순서로 호출하게 하고, opencode 가 돌려준 결과를 검사한다."""
    script = [("tool", "skill", {"name": skill}),
              ("tool", "bash", {"command": command, "description": "run bundled script"}), "DONE"]
    with FakeLLM(script=script) as llm:
        proc = sb.opencode(["run", "-m", "fake/echo", "--auto", "go"], cwd, timeout=300,
                           extra_env={"OPENCODE_CONFIG_CONTENT": json.dumps(llm.provider_config()), "PWD": str(cwd)})
        reqs = llm.main_requests()
    tool_msgs = [llm.message_text(m) for r in reqs[-1:] for m in r["messages"] if m["role"] == "tool"]
    skill_msg = next((t for t in tool_msgs if "<skill_content" in t), "")
    script_msg = tool_msgs[-1] if len(tool_msgs) > 1 else ""
    base = re.search(r"Base directory for this skill: (.+)", skill_msg)
    check(f"[fake model] {label}: skill tool returns SKILL.md + base directory", bool(base) and "scripts" in skill_msg,
          skill_msg[-300:] + proc.stderr[-300:])
    if base:
        print(f"       info: base directory line = {base.group(1).strip()}", flush=True)
    check(f"[fake model] {label}: bash tool ran the bundled script", marker in script_msg, script_msg[:400] + proc.stderr[-300:])


try:
    shutil.rmtree(HERE / "out", ignore_errors=True)
    h = run(SCRIPT, "--help")
    check("script --help exits 0", h.returncode == 0 and "--out" in h.stdout, h.stderr)

    p = run(SCRIPT, "data/sales.csv", "--out", "out/report.html")
    check("script exits 0", p.returncode == 0, p.stderr)
    summary = json.loads(p.stdout) if p.returncode == 0 else {}
    check("report file written", OUT.is_file())
    html = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    check("inline SVG chart present", html.count("<svg") == 1 and "<polyline" in html and html.count('class="bar"') == 12)
    check("summary table present", "<table>" in html and "서울" in html and "합계" in html)
    check("all template placeholders filled", "{{" not in html)
    check("no external assets (no CDN, no JS, no links)",
          not re.search(r"https?://|<script|<link rel=\"stylesheet\"|@import|src=", html), "found an external reference")
    check("summary JSON numbers", summary.get("best_month", {}).get("month") == "2025-11"
          and summary.get("total_revenue") == 67639000, json.dumps(summary)[:300])
    busan = [r for r in summary.get("regions_detail", []) if r["region"] == "부산"]
    check("planted dip detected (Busan Jul-Sep)", bool(busan) and busan[0]["dip_months"] == ["2025-07", "2025-08", "2025-09"])

    p = run(SCRIPT, "data/nope.csv")
    check("missing CSV exits 2", p.returncode == 2 and "error" in p.stderr, p.stderr)
    bad = HERE / "out" / "bad.csv"
    bad.write_text("month,region,units\n2025-01,서울,3\n", encoding="utf-8")
    p = run(SCRIPT, "out/bad.csv", "--out", "out/x.html")
    check("missing column exits 2", p.returncode == 2 and "revenue" in p.stderr, p.stderr)

    with Sandbox("s4a") as sb:
        skills = sb.debug_skills(cwd=HERE)
        found = [s for s in skills if s["name"] == "html-report"]
        check("skill discovered", bool(found))
        check("description has Korean triggers", bool(found) and "HTML 리포트" in found[0]["description"])
        scripted_skill_run(sb, HERE, 'html-report', f"python {(HERE / SCRIPT).as_posix()} data/sales.csv --out out/report.html", "output_absolute", 'html-report')
        if model_enabled():
            shutil.rmtree(HERE / "out", ignore_errors=True)
            out = sb.run_model("html-report 스킬로 data/sales.csv 의 HTML 리포트를 만들어 줘. 인사이트 3가지도 요약해 줘.", cwd=HERE)
            model_check("model loaded the skill", out, skill_loaded(out, "html-report"))
            model_check("report was generated by the script", out, OUT.is_file() and "build_report.py" in out)
            model_check("answer gives the path to open", out, "report.html" in out and "11" in out)
finally:
    shutil.rmtree(HERE / "out", ignore_errors=True)

finish()
